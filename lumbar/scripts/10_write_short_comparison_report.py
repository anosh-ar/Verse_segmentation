"""Step 10: the table of the short report: Dice per vertebra on the VerSe test set for the
model trained on TotalSegmentator and the one trained on the VerSe19 training set.

What it does
  Writes Table 2 of the original project's report (same layout: L1-L5, All, Limit, n),
  restricted to the VerSe test set (VerSe19 validation + test), with one row per model.
  Every number is read from the step-6 results; nothing is typed in by hand.

Needs
  outputs/evaluation_totalseg_1.5mm/dice_per_level.csv   TotalSegmentator-trained model (copied
                                                         from the original project, step 6 there)
  outputs/evaluation_verse_1mm/dice_per_level.csv        VerSe-trained model (step 6 here)

Output
  report/comparison_table.tex   included by report/short_comparison_report.tex (hand-written
                                paragraph); build the PDF with: tectonic report/short_comparison_report.tex

    python scripts/10_write_short_comparison_report.py
"""

import pandas as pd

from lumbar.labels import TARGET_LEVELS
from lumbar.sources import PROJECT_ROOT

OUTPUTS = PROJECT_ROOT / "outputs"
TABLE = PROJECT_ROOT / "report" / "comparison_table.tex"
VERSE_TEST_SET = "VerSe19 val + test (out-of-domain)"   # group name written by step 6
MODELS = {  # row name -> (evaluation tag, voxel size in mm)
    "TotalSegmentator (902 scans)": ("totalseg_1.5mm", 1.5),
    "VerSe19 training set (56 scans)": ("verse_1mm", 1.0),
}


def dice_cell(s: pd.Series) -> str:
    return f"{s.mean():.2f} / {s.median():.2f}".replace("0.", ".")


def main():
    L = ["% Generated by lumbar/scripts/10_write_short_comparison_report.py -- do not edit by hand.",
         r"\begin{table}[h]", r"\centering\footnotesize",
         r"\caption{Dice per vertebra on the VerSe test set (VerSe19 validation + test, 67 scans), mean / median, "
         r"for the two models (layout of Table~2 of the original report). \emph{Limit}: Dice of the ground truth "
         r"after resampling to the model's voxel size and back, i.e.\ the highest score possible at that voxel "
         r"size. $n$: number of scored vertebrae.}",
         r"\label{tab:dice}", r"\begin{tabular}{@{}lcccccccc@{}}", r"\toprule",
         r"Trained on (voxel size) & L1 & L2 & L3 & L4 & L5 & All & Limit & $n$\\", r"\midrule"]
    for model, (tag, mm) in MODELS.items():
        lv = pd.read_csv(OUTPUTS / f"evaluation_{tag}" / "dice_per_level.csv")
        d = lv[(lv["group"] == VERSE_TEST_SET) & ~lv["fragment"]]
        levels = " & ".join(dice_cell(d.loc[d["level"] == n, "dice"]) for n in TARGET_LEVELS)
        limit = f"{d['dice_ceiling'].mean():.2f}".replace("0.", ".")
        L.append(f"{model} ({mm:g}\\,mm) & {levels} & \\textbf{{{dice_cell(d['dice'])}}} & {limit} & {len(d)}\\\\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    TABLE.parent.mkdir(parents=True, exist_ok=True)
    TABLE.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"[report] table -> {TABLE}")


if __name__ == "__main__":
    main()
